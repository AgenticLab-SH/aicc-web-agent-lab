import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { inspectMaintenance } from '../tools/platform/inspect/inspect-guidance-maintenance.mjs';

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'guidance-maintenance-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const options = { aiccRoot: path.join(root, 'source'), codexHome: path.join(root, '.codex'), stateRoot: path.join(root, 'state'), now: new Date('2026-10-05T00:00:00Z') };
  const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
  const common = '## Rules\n\n- Keep approved scope.\n';
  const deployed = '<!-- Generated by AICC; edit guidance/directives/fragments, not this file. -->\n' + common;
  write(path.join(options.aiccRoot, 'guidance/directives/fragments/common.md'), common);
  write(path.join(options.aiccRoot, 'guidance/directives/generated/codex/AGENTS.md'), deployed);
  write(path.join(options.codexHome, 'AGENTS.md'), deployed);
  write(path.join(options.codexHome, 'config.toml'), 'approval_policy = "never"\nsandbox_mode = "danger-full-access"\n');
  write(path.join(options.stateRoot, 'inventory/skill-catalog.json'), JSON.stringify({ generatedAt: options.now.toISOString(), summary: {}, skills: [], instructionFiles: [] }));
  return { options, write };
}

test('unchanged guidance stays quiet and official freshness expires independently', t => {
  const { options } = fixture(t);
  assert.equal(inspectMaintenance(options).changed, true);
  assert.equal(fs.existsSync(path.join(options.stateRoot, 'inventory/guidance-maintenance-state.json')), false);
  const first = inspectMaintenance({ ...options, writeState: true, markReviewed: true });
  assert.equal(first.ok, true);
  assert.equal(first.officialReviewDue, false);
  const next = inspectMaintenance({ ...options, now: new Date('2026-10-06T00:00:00Z') });
  assert.equal(next.changed, false);
  assert.equal(next.findingsChanged, false);
  assert.equal(next.officialReviewDue, false);
  assert.equal(next.catalogRefreshDue, false);
  assert.equal(inspectMaintenance({ ...options, now: new Date('2026-10-12T00:00:00Z') }).officialReviewDue, true);
  assert.equal(inspectMaintenance({ ...options, now: new Date('2026-10-12T00:00:00Z') }).catalogRefreshDue, true);
});

test('config conflicts and deployed drift are findings without automatic config mutation', t => {
  const { options, write } = fixture(t);
  const config = path.join(options.codexHome, 'config.toml');
  write(config, 'sandbox_mode = "danger-full-access"\ndefault_permissions = ":workspace"\n');
  write(path.join(options.codexHome, 'AGENTS.md'), 'A user changed this copy.\n');
  const before = fs.readFileSync(config, 'utf8');
  const report = inspectMaintenance(options);
  assert.equal(report.ok, false);
  assert.ok(report.issues.some(issue => issue.code === 'mixed-permission-configuration'));
  assert.ok(report.issues.some(issue => issue.code === 'directive-delivery-drift'));
  assert.equal(fs.readFileSync(config, 'utf8'), before);
});

test('project instructions are watched and a missing catalog cannot pass as healthy', t => {
  const { options, write } = fixture(t);
  const instruction = path.join(options.aiccRoot, 'project/AGENTS.md');
  const catalog = path.join(options.stateRoot, 'inventory/skill-catalog.json');
  write(instruction, 'Preserve the project.\n');
  write(catalog, JSON.stringify({ generatedAt: options.now.toISOString(), summary: {}, skills: [], instructionFiles: [instruction] }));
  inspectMaintenance({ ...options, writeState: true });
  assert.equal(inspectMaintenance(options).changed, false);
  write(instruction, 'Use the new canonical source.\n');
  assert.ok(inspectMaintenance(options).changedPaths.includes(instruction));
  fs.unlinkSync(catalog);
  assert.ok(inspectMaintenance(options).issues.some(issue => issue.code === 'missing-skill-catalog'));
});
