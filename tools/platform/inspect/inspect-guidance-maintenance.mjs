#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const excluded = new Set(['.git', 'node_modules', '.venv', 'venv', '__pycache__', '.backups', 'backups']);
const sha = value => crypto.createHash('sha256').update(value).digest('hex');

function filesUnder(root, files) {
  if (!fs.existsSync(root)) return;
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    if (entry.isSymbolicLink() || excluded.has(entry.name)) continue;
    const file = path.join(root, entry.name);
    if (entry.isDirectory()) filesUnder(file, files);
    else if (entry.isFile() && /\.(md|yaml|yml|toml|json|mjs|ps1)$/i.test(entry.name)) files.add(file);
  }
}

export function inspectMaintenance(options = {}) {
  const aiccRoot = path.resolve(options.aiccRoot || defaultRoot);
  const codexHome = path.resolve(options.codexHome || path.join(os.homedir(), '.codex'));
  const stateRoot = path.resolve(options.stateRoot || path.join(path.dirname(codexHome), '.ai-control-center'));
  const now = options.now || new Date();
  const statePath = path.join(stateRoot, 'inventory', 'guidance-maintenance-state.json');
  const previous = fs.existsSync(statePath) ? JSON.parse(fs.readFileSync(statePath, 'utf8')) : {};
  const watched = new Set();
  filesUnder(path.join(aiccRoot, 'guidance'), watched);
  filesUnder(path.join(codexHome, 'skills'), watched);
  filesUnder(path.join(path.dirname(codexHome), '.agents', 'skills'), watched);
  for (const relative of ['AGENTS.md', 'docs/agent-operations.md', 'docs/agent-engineering-direction.md', 'docs/agent-platform-baseline.md', 'docs/agent-context-optimization.md', 'docs/skill-ecosystem.md', 'tools/platform/test/Test-AgentHomeDirectives.ps1', 'tools/platform/inspect/inspect-skill-ecosystem.mjs', 'tools/platform/inspect/inspect-guidance-maintenance.mjs']) {
    const file = path.join(aiccRoot, relative);
    if (fs.existsSync(file)) watched.add(file);
  }
  for (const relative of ['AGENTS.md', 'AGENTS.override.md', 'config.toml', 'hooks.json', 'agents/luna_worker.toml']) {
    const file = path.join(codexHome, relative);
    if (fs.existsSync(file)) watched.add(file);
  }
  // Use the existing catalog to track project and installed publisher entrypoints.
  // A full recursive project scan is done only when the review actually needs it.
  const catalogPath = path.join(stateRoot, 'inventory', 'skill-catalog.json');
  const catalog = fs.existsSync(catalogPath) ? JSON.parse(fs.readFileSync(catalogPath, 'utf8')) : null;
  for (const skill of catalog?.skills || []) {
    if (skill.status !== 'cached' && fs.existsSync(skill.canonicalPath)) watched.add(skill.canonicalPath);
  }
  for (const file of catalog?.instructionFiles || []) if (fs.existsSync(file)) watched.add(file);
  const hashes = Object.fromEntries([...watched].sort().map(file => [file, sha(fs.readFileSync(file))]));
  const fingerprint = sha(JSON.stringify(hashes));
  const changedPaths = [...new Set([...Object.keys(hashes), ...Object.keys(previous.hashes || {})])]
    .filter(file => hashes[file] !== previous.hashes?.[file]);
  const issues = [];
  const commonPath = path.join(aiccRoot, 'guidance/directives/fragments/common.md');
  const homePath = path.join(codexHome, 'AGENTS.md');
  const generatedPath = path.join(aiccRoot, 'guidance/directives/generated/codex/AGENTS.md');
  const read = file => fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const common = read(commonPath);
  const home = read(homePath);
  const generated = read(generatedPath);
  if (common === null || home === null || generated === null) issues.push({ code: 'missing-directive-copy' });
  else {
    const expected = '<!-- Generated by AICC; edit guidance/directives/fragments, not this file. -->\n' + common.trim() + '\n';
    if (home !== generated || home !== expected) issues.push({ code: 'directive-delivery-drift' });
    if (Buffer.byteLength(home) > 2048 || home.trimEnd().split(/\r?\n/).length > 12) {
      issues.push({ code: 'directive-budget', bytes: Buffer.byteLength(home), lines: home.trimEnd().split(/\r?\n/).length });
    }
  }
  const configText = read(path.join(codexHome, 'config.toml')) || '';
  const topLevel = configText.split(/^\s*\[/m)[0];
  const sandbox = topLevel.match(/^sandbox_mode\s*=\s*"([^"]+)"/m)?.[1];
  const permission = topLevel.match(/^default_permissions\s*=\s*"([^"]+)"/m)?.[1];
  if (sandbox && permission) issues.push({ code: 'mixed-permission-configuration' });
  // This is a consistency check, not a command to change the user's chosen policy.
  if (catalog) {
    if (catalog.summary.aiccDeliveryIssueCount) issues.push({ code: 'catalog-delivery-drift', count: catalog.summary.aiccDeliveryIssueCount });
    if (catalog.summary.effectiveDuplicateNameCount) issues.push({ code: 'catalog-name-collision', count: catalog.summary.effectiveDuplicateNameCount });
    if (catalog.summary.aiccImplicitDescriptionCharacters > 5000) issues.push({ code: 'implicit-description-budget', characters: catalog.summary.aiccImplicitDescriptionCharacters });
  } else issues.push({ code: 'missing-skill-catalog' });
  const catalogRefreshDue = !catalog?.generatedAt || now.getTime() - Date.parse(catalog.generatedAt) >= 7 * 86400000;
  const observed = now.toISOString();
  const lastOfficialReview = options.markReviewed ? observed : previous.lastOfficialReview;
  const officialReviewDue = !lastOfficialReview || now.getTime() - Date.parse(lastOfficialReview) >= 7 * 86400000;
  const issueFingerprint = sha(JSON.stringify(issues));
  const report = {
    ok: issues.length === 0,
    changed: fingerprint !== previous.fingerprint,
    findingsChanged: issueFingerprint !== previous.issueFingerprint,
    officialReviewDue,
    catalogRefreshDue,
    watchedFileCount: watched.size,
    changedPaths,
    issues,
    measurements: { globalEntryBytes: home === null ? null : Buffer.byteLength(home), implicitDescriptionCharacters: catalog?.summary.aiccImplicitDescriptionCharacters ?? null },
    statePath
  };
  if (options.writeState) {
    fs.mkdirSync(path.dirname(statePath), { recursive: true });
    fs.writeFileSync(statePath, JSON.stringify({ checkedAt: observed, fingerprint, issueFingerprint, hashes, lastOfficialReview: lastOfficialReview || null, issues }, null, 2) + '\n');
  }
  return report;
}

function main() {
  const options = {};
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i += 1) {
    const key = args[i];
    if (key === '--aicc-root') options.aiccRoot = args[++i];
    else if (key === '--codex-home') options.codexHome = args[++i];
    else if (key === '--state-root') options.stateRoot = args[++i];
    else if (key === '--write-state') options.writeState = true;
    else if (key === '--mark-reviewed') options.markReviewed = true;
    else if (key === '--help') {
      process.stdout.write('Read-only guidance fingerprint and consistency check. Optional --write-state saves only hashes and findings. --mark-reviewed records an actually completed official-source review.\n');
      return;
    } else throw new Error(`Unknown argument: ${key}`);
  }
  if (options.markReviewed && !options.writeState) throw new Error('--mark-reviewed requires --write-state');
  const report = inspectMaintenance(options);
  process.stdout.write(JSON.stringify(report, null, 2) + '\n');
  if (!report.ok) process.exitCode = 1;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
